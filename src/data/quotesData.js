export function formatSourceLine(quote) {
  const chapterSuffix = quote.chapterOrSection ? ` ${quote.chapterOrSection}` : ''
  if (quote.quoteType === 'translation') {
    return `${quote.author} · 『${quote.sourceTitle}』${chapterSuffix}`
  }
  return `${quote.author} 『${quote.sourceTitle}』${chapterSuffix}의 뜻을 바탕으로 풀어쓴 문장`
}

